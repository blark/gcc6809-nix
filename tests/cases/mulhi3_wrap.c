int main(void)
{
    unsigned int i;
    for (i = 0; i < sizeof(cases) / sizeof(cases[0]); ++i) {
        volatile unsigned int a = cases[i].a;
        volatile unsigned int b = cases[i].b;
        if (a * b != cases[i].p)
            return (int)i + 1;
    }
    return 0;
}
